@Composable
fun JourneyScreen(songs: SongDao, intelligence: IntelligenceDao, fa: Boolean, pd: Boolean, onPlay: (List<Song>, String) -> Unit) {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    var start by remember { mutableIntStateOf(Moods.SAD) }
    var end by remember { mutableIntStateOf(Moods.HAPPY) }
    var minutes by remember { mutableIntStateOf(45) }
    var energy by remember { mutableFloatStateOf(.65f) }
    var familiarity by remember { mutableFloatStateOf(.6f) }
    var onlineAssist by remember { mutableStateOf(false) }
    var generated by remember { mutableStateOf<List<Song>>(emptyList()) }
    var source by remember { mutableStateOf("") }
    var loading by remember { mutableStateOf(false) }
    var message by remember { mutableStateOf("") }
    val saved by intelligence.journeys().collectAsState(initial = emptyList())

    fun config() = JourneyConfig(start, end, minutes, energy, familiarity)
    suspend fun generate() {
        loading = true; message = ""
        withContext(Dispatchers.IO) {
            val all = songs.playlist(-1); val dna = intelligence.taste()
            generated = JourneyEngine.generate(all, dna, config())
            source = "local"
            if (onlineAssist && AiSettings.enabled(context) && ProviderRegistry(context).configured()) {
                OnlineGate(context).check()?.let { message = it; return@withContext }
                try {
                    OnlineGate(context).record()
                    val candidates = generated.take(30)
                    val data = JSONArray()
                    candidates.forEach { data.put(JSONObject().put("id", it.id).put("mood", it.mood).put("bpm", it.bpm.toInt()).put("energy", it.energy)) }
                    val prompt = "Reorder only these candidate IDs for a gradual mood journey from $start to $end in $minutes minutes. Return JSON array of IDs only. Preserve diversity and smooth energy/BPM transitions. Candidates: $data"
                    val response = ProviderRegistry(context).conversational.complete("You are a constrained playlist optimizer. Never invent IDs.", prompt)
                    val ids = JSONArray(response.removePrefix("```json").removeSuffix("```").trim())
                    val ordered = mutableListOf<Song>()
                    for (i in 0 until ids.length()) candidates.firstOrNull { it.id == ids.getLong(i) }?.let { if (it !in ordered) ordered += it }
                    if (ordered.isNotEmpty()) {
                        generated = ordered + generated.filter { it !in ordered }
                        source = "online_assisted"
                    }
                    intelligence.log(AiProcessingLog(provider = "Gemini", model = AiSettings.model(context), processingMode = AiSettings.mode(context), operation = "journey", status = "success", createdAt = System.currentTimeMillis()))
                } catch (e: Exception) {
                    message = e.message ?: "Online assistance failed; local journey is available"
                    intelligence.log(AiProcessingLog(provider = "Gemini", model = AiSettings.model(context), processingMode = AiSettings.mode(context), operation = "journey", status = "fallback", createdAt = System.currentTimeMillis(), details = e.message.orEmpty().take(300)))
                }
            }
        }
        loading = false
    }

    LazyColumn(Modifier.fillMaxSize().padding(16.dp), verticalArrangement = Arrangement.spacedBy(12.dp)) {
        item { V3Header(tr(fa, "Mood Journey", "سفر حال‌وهوا"), tr(fa, "Your selected moods guide the transition", "حال‌وهوای انتخابی شما مسیر را می‌سازد"), Icons.Default.Route) }
        item { V3Card {
            Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.SpaceBetween) {
                Button(onClick = { start = Moods.all[(Moods.all.indexOf(start) + 1) % Moods.all.size] }) { Text(tr(fa, "From: ", "از: ") + Moods.name(start, fa)) }
                Button(onClick = { end = Moods.all[(Moods.all.indexOf(end) + 1) % Moods.all.size] }) { Text(tr(fa, "To: ", "به: ") + Moods.name(end, fa)) }
            }
            Text(tr(fa, "Duration: $minutes minutes", "مدت: $minutes دقیقه"))
            Slider(value = minutes.toFloat(), onValueChange = { minutes = it.toInt() }, valueRange = 15f..120f)
            Text(tr(fa, "Journey intensity", "شدت سفر"))
            Slider(value = energy, onValueChange = { energy = it })
            Text(tr(fa, "Familiarity preference", "ترجیح آهنگ آشنا"))
            Slider(value = familiarity, onValueChange = { familiarity = it })
            Row(verticalAlignment = Alignment.CenterVertically) {
                Column(Modifier.weight(1f)) { Text(tr(fa, "Online sequence assistance", "کمک آنلاین به ترتیب آهنگ‌ها")); Text(tr(fa, "Sends only selected IDs/audio features, not audio", "فقط شناسه و ویژگی‌ها، نه فایل صوتی"), style = MaterialTheme.typography.bodySmall) }
                Switch(checked = onlineAssist, onCheckedChange = { onlineAssist = it })
            }
            Button(enabled = !loading, onClick = { scope.launch { generate() } }, modifier = Modifier.fillMaxWidth()) { Icon(Icons.Default.Route, null); Spacer(Modifier.width(8.dp)); Text(tr(fa, "Generate journey", "ساخت سفر")) }
            if (loading) LoadingLine()
            if (source.isNotBlank()) Text(tr(fa, "Source: $source", "منبع: $source"), style = MaterialTheme.typography.bodySmall)
            if (message.isNotBlank()) Text(message, color = MaterialTheme.colorScheme.error)
        } }
        if (generated.isNotEmpty()) {
            item {
                Row {
                    Button(onClick = { onPlay(generated, "journey") }, modifier = Modifier.weight(1f)) { Icon(Icons.Default.PlayArrow, null); Text(tr(fa, "Play", "پخش")) }
                    Spacer(Modifier.width(8.dp))
                    OutlinedButton(onClick = {
                        scope.launch(Dispatchers.IO) {
                            intelligence.addJourney(MoodJourney(name = "${Moods.name(start, true)} → ${Moods.name(end, true)}", startingMood = start, targetMood = end, requestedMinutes = minutes, energy = energy, familiarity = familiarity, songIds = generated.joinToString(",") { it.id.toString() }, generatedAt = System.currentTimeMillis()))
                        }
                    }, modifier = Modifier.weight(1f)) { Icon(Icons.Default.BookmarkAdd, null); Text(tr(fa, "Save", "ذخیره")) }
                }
            }
            items(generated.size, key = { "${generated[it].id}-${it}" }) { index ->
                val song = generated[index]
                ElevatedCard(colors = CardDefaults.elevatedCardColors(containerColor = MaterialTheme.colorScheme.surfaceVariant)) {
                    Row(Modifier.padding(10.dp), verticalAlignment = Alignment.CenterVertically) {
                        Text("${index + 1}", color = MaterialTheme.colorScheme.primary, modifier = Modifier.width(28.dp))
                        Column(Modifier.weight(1f)) { Text(song.title, maxLines = 1, overflow = TextOverflow.Ellipsis); Text(Moods.name(song.mood, fa) + " • " + clock(song.duration, pd), style = MaterialTheme.typography.bodySmall) }
                        TextButton(onClick = {
                            scope.launch(Dispatchers.IO) {
                                generated = JourneyEngine.replace(generated, index, songs.playlist(-1), intelligence.taste(), config())
                            }
                        }) { Text(tr(fa, "Replace", "جایگزینی")) }
                    }
                }
            }
        }
        if (saved.isNotEmpty()) item { Text(tr(fa, "Saved journeys", "سفرهای ذخیره‌شده"), style = MaterialTheme.typography.titleMedium) }
        items(saved, key = { it.journeyId }) { journey ->
            V3Card {
                Text(journey.name, fontWeight = FontWeight.Bold)
                Text(tr(fa, "${journey.requestedMinutes} min • ${TimeRanges.label(journey.generatedAt)}", "${journey.requestedMinutes} دقیقه • ${TimeRanges.label(journey.generatedAt)}"), style = MaterialTheme.typography.bodySmall)
                Row {
                    TextButton(onClick = {
                        scope.launch(Dispatchers.IO) {
                            val list = journey.songIds.split(',').mapNotNull { it.toLongOrNull() }.mapNotNull { songs.get(it) }
                            withContext(Dispatchers.Main) { generated = list; start = journey.startingMood; end = journey.targetMood; minutes = journey.requestedMinutes }
                        }
                    }) { Text(tr(fa, "Open", "بازکردن")) }
                    TextButton(onClick = {
                        start = journey.startingMood; end = journey.targetMood; minutes = journey.requestedMinutes
                        energy = journey.energy; familiarity = journey.familiarity
                        scope.launch { generate() }
                    }) { Text(tr(fa, "Rebuild with DNA", "بازسازی با DNA")) }
                    TextButton(onClick = { scope.launch(Dispatchers.IO) { intelligence.deleteJourney(journey.journeyId) } }) { Text(tr(fa, "Delete", "حذف")) }
                }
            }
        }
    }
}

@Composable
fun SmartDjScreen(fa: Boolean, onStart: (String) -> Unit) {
    val context = LocalContext.current
    val prefs = remember { AiSettings.prefs(context) }
    var enabled by remember { mutableStateOf(prefs.getBoolean("djEnabled", false)) }
    var mode by remember { mutableStateOf(prefs.getString("djMode", "party") ?: "party") }
    var crossfade by remember { mutableIntStateOf(prefs.getInt("djCrossfade", 6)) }
    var bpm by remember { mutableStateOf(prefs.getBoolean("djBpm", true)) }
    var energy by remember { mutableStateOf(prefs.getBoolean("djEnergy", true)) }
    var avoid by remember { mutableStateOf(prefs.getBoolean("djAvoidSimilar", true)) }
    var familiar by remember { mutableStateOf(prefs.getBoolean("djFamiliar", true)) }
    var discovery by remember { mutableStateOf(prefs.getBoolean("djDiscovery", true)) }
    var normalize by remember { mutableStateOf(prefs.getBoolean("djNormalize", true)) }
    var noRepeat by remember { mutableIntStateOf(prefs.getInt("djNoRepeat", 30)) }
    val modes = listOf("party", "chill", "emotional", "workout", "night", "nostalgic", "discovery")
    LazyColumn(Modifier.fillMaxSize().padding(16.dp), verticalArrangement = Arrangement.spacedBy(12.dp)) {
        item { V3Header(tr(fa, "Smart DJ", "دی‌جِی هوشمند"), tr(fa, "Two synchronized players create the actual overlap", "دو پخش‌کننده هماهنگ، هم‌پوشانی واقعی می‌سازند"), Icons.Default.GraphicEq) }
        item { V3Card {
            Row(verticalAlignment = Alignment.CenterVertically) { Text(tr(fa, "Enable Smart DJ", "فعال‌کردن دی‌جِی"), Modifier.weight(1f)); Switch(checked = enabled, onCheckedChange = { enabled = it; prefs.edit().putBoolean("djEnabled", it).apply() }) }
            Text(tr(fa, "DJ mode", "حالت دی‌جِی"))
            LazyRow(horizontalArrangement = Arrangement.spacedBy(6.dp)) {
                items(modes.size) { index -> FilterChip(selected = mode == modes[index], onClick = { mode = modes[index]; prefs.edit().putString("djMode", mode).apply() }, label = { Text(modes[index]) }) }
            }
            Text(tr(fa, "Crossfade: $crossfade seconds", "کراس‌فید: $crossfade ثانیه"))
            Slider(value = crossfade.toFloat(), onValueChange = { crossfade = it.toInt(); prefs.edit().putInt("djCrossfade", crossfade).apply() }, valueRange = 2f..12f)
            Text(tr(fa, "No repeat window: $noRepeat tracks", "فاصله تکرار: $noRepeat آهنگ"))
            Slider(value = noRepeat.toFloat(), onValueChange = { noRepeat = it.toInt(); prefs.edit().putInt("djNoRepeat", noRepeat).apply() }, valueRange = 5f..100f)
            DjSwitch(tr(fa, "BPM matching", "تطبیق BPM"), bpm) { bpm = it; prefs.edit().putBoolean("djBpm", it).apply() }
            DjSwitch(tr(fa, "Energy matching", "تطبیق انرژی"), energy) { energy = it; prefs.edit().putBoolean("djEnergy", it).apply() }
            DjSwitch(tr(fa, "Avoid similar consecutive artists", "اجتناب از هنرمند مشابه پیاپی"), avoid) { avoid = it; prefs.edit().putBoolean("djAvoidSimilar", it).apply() }
            DjSwitch(tr(fa, "Prefer familiar songs", "اولویت آهنگ آشنا"), familiar) { familiar = it; prefs.edit().putBoolean("djFamiliar", it).apply() }
            DjSwitch(tr(fa, "Allow discoveries", "اجازه آهنگ‌های کشف‌شده"), discovery) { discovery = it; prefs.edit().putBoolean("djDiscovery", it).apply() }
            DjSwitch(tr(fa, "Volume normalization", "نرمال‌سازی صدا"), normalize) { normalize = it; prefs.edit().putBoolean("djNormalize", it).apply() }
            Text(tr(fa, "Fade length can be beat-quantized from BPM. Beat-grid/phase synchronization is not claimed without beat-position data.", "طول فید بر اساس BPM کوانتیزه می‌شود؛ بدون موقعیت ضرب، همگام‌سازی فاز ادعا نمی‌شود."), style = MaterialTheme.typography.bodySmall)
            Button(onClick = { prefs.edit().putBoolean("djEnabled", true).putString("djMode", mode).apply(); enabled = true; onStart(mode) }, modifier = Modifier.fillMaxWidth()) { Icon(Icons.Default.PlayArrow, null); Text(tr(fa, "Start Smart DJ", "شروع دی‌جِی")) }
        } }
    }
}
@Composable private fun DjSwitch(label: String, checked: Boolean, onChange: (Boolean) -> Unit) {
    Row(verticalAlignment = Alignment.CenterVertically) { Text(label, Modifier.weight(1f)); Switch(checked = checked, onCheckedChange = onChange) }
}
